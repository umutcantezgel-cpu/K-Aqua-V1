for k, v in patch.items():
    parts = k.split(".")
    curr = az
    for p in parts[:-1]:
        if p.endswith("]"):
            p_name, idx = p[:-1].split("[")
            idx = int(idx)
            curr = curr[p_name][idx]
        else:
            if p not in curr: curr[p] = {}
            curr = curr[p]
    
    last = parts[-1]
    if last.endswith("]"):
        p_name, idx = last[:-1].split("[")
        idx = int(idx)
        curr[p_name][idx] = v
    else:
        curr[last] = v

